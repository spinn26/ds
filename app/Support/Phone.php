<?php

namespace App\Support;

/**
 * Нормализация телефонов для сравнения.
 *
 * В базе один и тот же номер лежит во всех видах: «+7 904 390 46 79»,
 * «+79043904679», «79043904679», «89043904679». Сравнение строк даёт ложное
 * «не найдено» → интеграции плодят дубли клиентов. Канон для сверки —
 * ПОСЛЕДНИЕ 10 ЦИФР: они одинаковы у 7/8-префиксов (РФ) и у КЗ (7707…/8707…).
 */
final class Phone
{
    /** SQL-выражение с тем же каноном, для сравнения на стороне БД. */
    public const SQL_NORM = "right(regexp_replace(coalesce(%s, ''), '[^0-9]', '', 'g'), 10)";

    /**
     * Последние 10 цифр номера или null, если цифр меньше 10 (обрывки вроде
     * «12345» матчить нельзя — склеит разных людей).
     */
    public static function norm(?string $phone): ?string
    {
        $digits = preg_replace('/\D+/', '', (string) $phone);

        return strlen($digits) >= 10 ? substr($digits, -10) : null;
    }

    /**
     * Похож ли ввод на настоящий номер.
     *
     * Фронт валидирует libphonenumber-js (PhoneInput/vue-tel-input), бэкенд не
     * проверял формат вообще — и «+7 (150) 832-28-70» уезжал в базу, потому что
     * клиентскую проверку легко обойти (автозаполнение не шлёт @validate,
     * прямой POST на /auth/register — тем более).
     *
     * Правило для +7 (РФ/КЗ): код страны + 10 цифр, где код зоны/оператора
     * начинается с 3,4,6,7,8,9 (мобильные 9xx РФ и 7xx КЗ, городские 3xx/4xx/
     * 8xx РФ, 6xx/7xx КЗ). Коды на 0,1,2,5 не выданы — это и есть «150…».
     * Для прочих стран — только длина E.164, детальных правил не держим.
     */
    public static function isValid(?string $phone): bool
    {
        $digits = preg_replace('/\D+/', '', (string) $phone);
        if ($digits === '') {
            return false;
        }

        // Трунковый «8» = международный «7»: 8 900… и +7 900… — один номер.
        if (strlen($digits) === 11 && $digits[0] === '8') {
            $digits = '7' . substr($digits, 1);
        }
        // Номер без кода страны (10 цифр) считаем российским — но только если
        // он начинается с российского кода зоны 3/4/6/9. Ведущая «7» здесь
        // почти всегда означает не КЗ, а обрубленный «+7…» с потерянной
        // цифрой: такие лучше отбить, чем достроить.
        if (strlen($digits) === 10 && str_contains('3469', $digits[0])) {
            $digits = '7' . $digits;
        }

        if ($digits[0] === '7') {
            return strlen($digits) === 11 && str_contains('346789', $digits[1]);
        }

        return strlen($digits) >= 8 && strlen($digits) <= 15;
    }

    /** SQL-выражение нормализации для колонки (колонка уже в кавычках, если надо). */
    public static function sql(string $column): string
    {
        return sprintf(self::SQL_NORM, $column);
    }
}
